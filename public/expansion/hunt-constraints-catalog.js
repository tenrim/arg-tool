const sudoku = ['每一格是从1到9的数字', '每一行互不相同', '每一列互不相同'];
for (let boxRow = 0; boxRow < 3; boxRow++) for (let boxCol = 0; boxCol < 3; boxCol++) {
  const cells = [];
  for (let row = 0; row < 3; row++) for (let col = 0; col < 3; col++) cells.push((boxRow * 3 + row) * 9 + boxCol * 3 + col + 1);
  sudoku.push(`第[${cells.join(',')}]格互不相同`);
}
