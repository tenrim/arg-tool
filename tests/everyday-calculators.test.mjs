const near = (actual, expected, tolerance = 1e-8) =>
  assert(Math.abs(actual - expected) <= tolerance, `${actual} ≠ ${expected}`);
test('海拔气压：NWS 标准点、对流层值、反算与边界', () => {
  near(standardPressure(0), 101.325);
  near(pressureAltitude(101.325), 0);
  // NWS's published rounded pressure-altitude relation is an approximation,
  // rather than the different coefficients of an exact ISA implementation.
  assert(standardPressure(11000) > 22 && standardPressure(11000) < 23);
  for (const h of [-500, 1000, 5000, 11000]) near(pressureAltitude(standardPressure(h)), h, 1e-7);
  assert.throws(() => standardPressure(11001));
  assert.throws(() => pressureAltitude(0));
  assert.throws(() => calc('altitude-pressure', { mode: 'height', height: '' }));
});
test('水沸点：独立核对 IAPWS 原文第 7 页 Table 1 三个点及临界端点', () => {
  // Values read from the published table, not generated by our inverse routine.
  near(saturationPressure(273.16), 0.611657, 1e-6);
  near(saturationPressure(373.1243), 101.325, 0.0001);
  near(saturationPressure(647.096), 22064, 1e-7);
  near(boilingTemperature(101.325), 99.9743, 1e-5);
  near(boilingTemperature(22064), 373.946, 1e-7);
  assert(boilingTemperature(50) < boilingTemperature(101.325));
  assert(calc('water-boiling', { mode: 'height', height: 5000 }).temperature < 90);
  assert.throws(() => boilingTemperature(0.5));
  assert.throws(() => boilingTemperature(22065));
});
test('露点：饱和边界、常见室内值、表面判断、零下与空表面', () => {
  near(calc('dew-point', { air: 20, rh: 100, surface: 20 }).dew, 20);
  const a = calc('dew-point', { air: 20, rh: 50, surface: 10 });
  near(a.dew, 9.2701, 0.0001);
  assert.equal(a.condenses, false);
  assert.equal(calc('dew-point', { air: 20, rh: 50, surface: 8 }).condenses, true);
  assert.equal(calc('dew-point', { air: 20, rh: 50, surface: '' }).surface, null);
  assert(calc('dew-point', { air: -10, rh: 50 }).dew < -10);
  for (const rh of [0, 101, '']) assert.throws(() => calc('dew-point', { air: 20, rh }));
});
test('混水：热量守恒、目标配比、端点与不可能的条件', () => {
  near(
    calc('water-mixing', { mode: 'temperature', cold: 20, hot: 80, coldMass: 1, hotMass: 1 })
      .temperature,
    50,
  );
  const r = calc('water-mixing', { mode: 'amount', cold: 20, hot: 80, total: 6, target: 40 });
  near(r.hotMass, 2);
  near(r.coldMass, 4);
  near(
    calc('water-mixing', { mode: 'amount', cold: 20, hot: 80, total: 6, target: 20 }).hotMass,
    0,
  );
  assert.throws(() =>
    calc('water-mixing', { mode: 'amount', cold: 20, hot: 80, total: 2, target: 90 }),
  );
  assert.throws(() =>
    calc('water-mixing', { mode: 'temperature', cold: 20, hot: 80, coldMass: 0, hotMass: 0 }),
  );
  assert.throws(() =>
    calc('water-mixing', { mode: 'amount', cold: 20, hot: 20, total: 2, target: 20 }),
  );
});
test('加热：教材水比热算例、功率效率、零温差与错误条件', () => {
  const input = { mass: 1, initial: 20, target: 80, power: 1000, efficiency: 100 };
  const a = calc('heating-time', input);
  near(a.heat, 251160);
  near(a.seconds, 251.16);
  near(a.kwh, 0.06976666666666667);
  near(calc('heating-time', { ...input, efficiency: 50 }).seconds, 502.32);
  near(calc('heating-time', { ...input, target: 20 }).seconds, 0);
  for (const patch of [
    { efficiency: 0 },
    { efficiency: 101 },
    { power: 0 },
    { target: 10 },
    { mass: '' },
  ])
    assert.throws(() => calc('heating-time', { ...input, ...patch }));
});
